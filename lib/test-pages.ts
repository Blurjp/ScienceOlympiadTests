// URL and eligibility logic for public per-test pages
// (/tests/[topic]/[id]-[difficulty]-practice-test). Pure functions so the
// slug grammar and eligibility rules are unit-testable without a database.
import type { Test } from './types';

// The database difficulty domain (see lib/difficulty.ts: competition levels
// map onto these three values; 'State' shares 'Medium').
export const DIFFICULTY_SLUGS = ['easy', 'medium', 'hard'] as const;
export type DifficultySlug = (typeof DIFFICULTY_SLUGS)[number];

const DIFFICULTY_TO_SLUG: Record<string, DifficultySlug> = {
  Easy: 'easy',
  Medium: 'medium',
  Hard: 'hard',
};

const SLUG_TO_DIFFICULTY: Record<DifficultySlug, string> = {
  easy: 'Easy',
  medium: 'Medium',
  hard: 'Hard',
};

export function difficultySlug(difficulty: string): DifficultySlug {
  return DIFFICULTY_TO_SLUG[difficulty] ?? 'medium';
}

export function difficultyLabel(slug: string): string {
  return SLUG_TO_DIFFICULTY[slug as DifficultySlug] ?? 'Medium';
}

// Test ids look like `1770335271483-6mds2qpu1` — they contain a dash, so the
// slug grammar anchors on the SUFFIX: {id}-{easy|medium|hard}-practice-test.
const SLUG_PATTERN = /^(.+)-(easy|medium|hard)-practice-test$/;

export function parseTestSlug(
  slug: string
): { id: string; difficulty: DifficultySlug } | null {
  const match = SLUG_PATTERN.exec(slug);
  if (!match) return null;
  return { id: match[1], difficulty: match[2] as DifficultySlug };
}

export function buildTestSlug(id: string, difficulty: string): string {
  return `${id}-${difficultySlug(difficulty)}-practice-test`;
}

export function buildTestPath(
  topicSlug: string,
  id: string,
  difficulty: string
): string {
  return `/tests/${topicSlug}/${buildTestSlug(id, difficulty)}`;
}

/**
 * A test gets a public page only when it is original publisher content:
 * public AND generated by generate-test / generate-ai-test. Third-party
 * imports (URL imports and uploaded-PDF parses) and generate-from-pdf
 * output never get pages — the latter derives from someone else's exam and
 * an LLM can reproduce source questions near-verbatim, so it stays private
 * (and page-ineligible even if a row is ever flipped public by hand).
 */
export function isPageEligibleTest(
  test: { title: string; description?: string | null; isPublic?: boolean }
): boolean {
  // isPublic === false → explicitly private. Summaries from the public-only
  // queries carry no flag; they are public by construction.
  if (test.isPublic === false) return false;
  if (test.title.startsWith('Original Practice:')) return false;
  const description = test.description ?? '';
  if (
    description.startsWith('Imported from') ||
    description.startsWith('Parsed from')
  ) {
    return false;
  }
  return true;
}

/** Questions as rendered on the public page: stems and options only.
 * Correct answers and explanations stay behind "Start test". */
export interface PublicQuestionView {
  id: string;
  number: number;
  question: string;
  options: string[];
  points: number;
  category?: string;
}

export function toPublicQuestions(
  questions: Test['questions']
): PublicQuestionView[] {
  return questions.map((q, index) => ({
    id: q.id,
    number: index + 1,
    question: q.question,
    options: q.options ?? [],
    points: q.points,
    category: q.category || undefined,
  }));
}

export function formatTotalTime(totalTimeSeconds: number): string {
  const minutes = Math.max(1, Math.round(totalTimeSeconds / 60));
  return `${minutes} min`;
}
